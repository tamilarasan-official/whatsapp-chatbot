export function t(lang, key, vars = {}) {
  const table = STRINGS[lang] || STRINGS.en;
  const value = key.split('.').reduce((o, k) => (o ? o[k] : undefined), table)
    ?? key.split('.').reduce((o, k) => (o ? o[k] : undefined), STRINGS.en);
  if (typeof value !== 'string') return value;
  return value.replace(/{(\w+)}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

export function faqText(lang, faq) {
  const tr = FAQ_T[lang]?.[faq.id];
  return tr ? { question: tr[0], answer: tr[1] } : { question: faq.question, answer: faq.answer };
}

// Script-based detection: Devanagari -> hi, Tamil -> ta, otherwise null.
export function detectScript(text) {
  if (/[ऀ-ॿ]/.test(text)) return 'hi';
  if (/[஀-௿]/.test(text)) return 'ta';
  return null;
}
